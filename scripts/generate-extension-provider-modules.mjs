import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { globSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const aiDir = resolve(root, "packages/ai");
const manifest = JSON.parse(readFileSync(resolve(aiDir, "package.json"), "utf8"));
// Expand the public export pattern, including nested modules, not provider IDs.
assert.equal(manifest.exports["./providers/*"].import, "./dist/providers/*.js");
const modules = globSync("**/*.ts", { cwd: resolve(aiDir, "src/providers") })
	.filter((file) => !file.endsWith(".d.ts"))
	.map((file) => file.replaceAll("\\", "/").slice(0, -3))
	.sort();
const source = `// Generated by scripts/generate-extension-provider-modules.mjs. Do not edit.
${modules.map((name, index) => `import * as module${index} from "@earendil-works/pi-ai/providers/${name}";`).join("\n")}

export const providerModules: Record<string, unknown> = {
${modules.map((name, index) => `\t${JSON.stringify(name)}: module${index},`).join("\n")}
};
`;
const target = resolve(root, "packages/coding-agent/src/core/extensions/provider-modules.generated.ts");
const output = execFileSync(
	process.execPath,
	[resolve(root, "node_modules/@biomejs/biome/bin/biome"), "check", "--write", "--stdin-file-path", target],
	{ cwd: root, input: source, encoding: "utf8" },
);
if (process.argv.includes("--check")) {
	assert.ok(readFileSync(target, "utf8") === output, "Run node scripts/generate-extension-provider-modules.mjs");
} else {
	writeFileSync(target, output);
}
